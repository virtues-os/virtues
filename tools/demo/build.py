#!/usr/bin/env python3
"""Build the demo life: virtues-core/seeds/demo/life.sql.gz.

One file, one persona (Jules Arden), everything a demo box shows:

  backbone   three thin years, generated by gen-backbone.py (deterministic)
  week       the dense showcase week, frozen in week/week.sql.gz (the box
             derived its events and pages with model calls, so it is kept as
             data, not regenerated)

Steps, all in a scratch database that is dropped afterwards:
  migrate -> load backbone -> load week -> list every row in demo.rows with its
  bucket (-1 backbone, 0..6 week day) -> place it on today -> export.

The export is one `INSERT (cols) SELECT cols FROM json_populate_recordset(...)`
per table, in foreign-key order, generated columns left out, no BEGIN/COMMIT
(the installer wraps it in one transaction).

Usage: python3 tools/demo/build.py [--schema N] [--db virtues_demo_build] [--keep]

--schema N builds on the schema as of migration N. Use the oldest release the
demo box runs: the file then loads there and on everything newer.
Needs: psql, createdb/dropdb, sqlx-cli, and the roles the migrations grant
(virtues_face_reader, virtues_applet_writer), as on any dev machine.
"""
import argparse, gzip, json, os, subprocess, sys, tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "virtues-core/seeds/demo/life.sql.gz"
WEEK = REPO / "tools/demo/week/week.sql.gz"
PLACE = REPO / "deploy/demo/place.sql"

# The tables a demo life writes outside data_*/wiki_*. Product state the box
# makes for itself (auth, devices, settings, the getting-started chat) is not
# the life and is never exported.
APP_TABLES = ["app_chats", "app_chat_messages", "app_pages", "app_projects", "app_project_items",
              "app_assistant_memories", "app_applets", "app_applet_runs"]

def sh(*a, **kw):
    return subprocess.run(a, check=True, text=True, capture_output=True, **kw).stdout

def psql(db, sql=None, file=None, stdin=None):
    args = ["psql", "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1", "-d", db]
    args += ["-c", sql] if sql else ["-f", file] if file else []
    return subprocess.run(args, check=True, text=True, capture_output=True, input=stdin).stdout

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="virtues_demo_build")
    ap.add_argument("--keep", action="store_true", help="keep the scratch database")
    ap.add_argument("--schema", type=int, metavar="MIGRATION",
                    help="build on the schema as of this migration: the oldest release the file must "
                         "load on. Newer schemas load it too (new columns take their defaults).")
    a = ap.parse_args()
    db = a.db
    subprocess.run(["dropdb", "--if-exists", db], check=True)
    subprocess.run(["createdb", db], check=True)
    url = f"postgres:///{db}"
    print("migrate", flush=True)
    target = ["--target-version", str(a.schema)] if a.schema else []
    sh("sqlx", "migrate", "run", "--source", str(REPO / "virtues-core/migrations"), "--database-url", url, *target)

    before = {t: set(psql(db, f"SELECT id::text FROM {t}").split()) for t in APP_TABLES}

    with tempfile.TemporaryDirectory() as tmp:
        print("backbone", flush=True)
        sh(sys.executable, str(REPO / "tools/demo/gen-backbone.py"), "--out", tmp)
        for f in sorted(Path(tmp).glob("0*.sql")):
            psql(db, file=str(f))

    print("week", flush=True)
    psql(db, stdin=gzip.open(WEEK, "rt").read())

    print("membership", flush=True)
    psql(db, """
CREATE SCHEMA demo;
CREATE TABLE demo.rows (tbl text NOT NULL, id text NOT NULL, bucket smallint NOT NULL, PRIMARY KEY (tbl, id));
CREATE TABLE demo.buckets (bucket smallint PRIMARY KEY, landed date NOT NULL);
INSERT INTO demo.rows SELECT tbl, id, day FROM demo_week.rows;
INSERT INTO demo.buckets SELECT day, landed FROM demo_week.days;
DROP SCHEMA demo_week CASCADE;""")
    tables = psql(db, """SELECT c.table_name FROM information_schema.columns c
        JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
       WHERE c.table_schema = 'public' AND c.column_name = 'id' AND t.table_type = 'BASE TABLE'
         AND (c.table_name LIKE 'data\\_%' OR c.table_name LIKE 'wiki\\_%') ORDER BY 1""").split()
    for t in tables + APP_TABLES:
        keep = "true"
        if t in before and before[t]:
            keep = "id::text NOT IN (" + ",".join("'" + x.replace("'", "''") + "'" for x in before[t]) + ")"
        psql(db, f"INSERT INTO demo.rows SELECT '{t}', id::text, -1 FROM {t} WHERE {keep} ON CONFLICT DO NOTHING")
    psql(db, """INSERT INTO demo.buckets SELECT -1, max(d.date) FROM wiki_days d
                 JOIN demo.rows r ON r.tbl = 'wiki_days' AND r.id = d.id AND r.bucket = -1""")
    print(psql(db, "SELECT bucket, count(*) FROM demo.rows GROUP BY 1 ORDER BY 1").replace("\n", "  "), flush=True)

    print("place", flush=True)
    psql(db, file=str(PLACE))

    print("export", flush=True)
    members = psql(db, "SELECT DISTINCT tbl FROM demo.rows").split()
    # Foreign-key order: a table comes after every member table it references.
    deps = {t: set() for t in members}
    for child, parent in (l.split("|") for l in psql(db, """
        SELECT conrelid::regclass::text, confrelid::regclass::text FROM pg_constraint
         WHERE contype = 'f' AND connamespace = 'public'::regnamespace""").split()):
        if child in deps and parent in deps and child != parent:
            deps[child].add(parent)
    order, seen = [], set()
    def visit(t):
        if t in seen: return
        seen.add(t)
        for p in sorted(deps[t]): visit(p)
        order.append(t)
    for t in sorted(members): visit(t)

    parts = ["-- The demo life (fiction): Jules Arden's three-year backbone and showcase week.",
             "-- Built by tools/demo/build.py; installed by deploy/demo/install.sh. Do not edit by hand.",
             "CREATE SCHEMA IF NOT EXISTS demo;",
             "CREATE TABLE IF NOT EXISTS demo.rows (tbl text NOT NULL, id text NOT NULL, bucket smallint NOT NULL, PRIMARY KEY (tbl, id));",
             "CREATE TABLE IF NOT EXISTS demo.buckets (bucket smallint PRIMARY KEY, landed date NOT NULL);"]
    def dump(qualified, where):
        schema, _, name = qualified.rpartition(".")
        schema = schema or "public"
        cols = psql(db, f"""SELECT string_agg(quote_ident(column_name), ', ' ORDER BY ordinal_position)
                              FROM information_schema.columns
                             WHERE table_schema = '{schema}' AND table_name = '{name}' AND is_generated = 'NEVER'""").strip()
        stmt = psql(db, f"""SELECT format('INSERT INTO %s (%s) SELECT %s FROM json_populate_recordset(NULL::%s, %L) ON CONFLICT DO NOTHING;',
                                          '{qualified}', '{cols}', '{cols}', '{qualified}', json_agg(to_jsonb(seed_row)))
                              FROM {qualified} seed_row WHERE {where} HAVING count(*) > 0""").strip()
        if stmt: parts.append(stmt)
    for t in order:
        dump(t, f"id::text IN (SELECT id FROM demo.rows WHERE tbl = '{t}')")
    dump("demo.buckets", "true")
    dump("demo.rows", "true")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(OUT, "wt", compresslevel=9) as f:
        f.write("\n".join(parts) + "\n")
    print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size // 1024} KiB), {len(order)} tables", flush=True)
    if not a.keep:
        subprocess.run(["dropdb", db], check=True)

if __name__ == "__main__":
    main()
